package net.shiroha233.roadweaver.features.landscape;

/**
 * 景观建筑类型枚举
 * 定义不同类型的景观建筑
 */
public enum LandscapeArchitectureType {
    /**
     * 凉亭 - 传统中式建筑，提供休息和观景功能
     */
    PAVILION,
    
    /**
     * 观景台 - 专门用于观景的平台，通常位于高处或水边
     */
    VIEWING_PLATFORM,
    
    /**
     * 小桥 - 跨越水体的桥梁，兼具功能和美观
     */
    SMALL_BRIDGE,
    
    /**
     * 亭子 - 小型休息建筑，通常有屋顶和座椅
     */
    GAZEBO,
    
    /**
     * 喷泉广场 - 以喷泉为中心的广场区域
     */
    FOUNTAIN_SQUARE,
    
    /**
     * 休息区 - 提供座椅和遮阳的休息区域
     */
    REST_AREA,
    
    /**
     * 雕塑花园 - 以雕塑和艺术装置为特色的花园
     */
    SCULPTURE_GARDEN,
    
    /**
     * 水景 - 小型瀑布、溪流等水景元素
     */
    WATER_FEATURE,
    
    /**
     * 迷宫花园 - 由植物构成的迷宫式花园
     */
    MAZE_GARDEN,
    
    /**
     * 钟楼 - 小型钟楼或钟塔建筑
     */
    CLOCK_TOWER
}
